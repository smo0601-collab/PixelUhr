#!/usr/bin/env python3
"""Embeds the web interface from data/ into the firmware as src/web_assets.h.

Every file is stored gzip-compressed (deterministic, level 9) and served with
"Content-Encoding: gzip". Run it after changing files in data/:

    python3 tools/embed_web.py

PlatformIO runs it automatically before each build (scripts/embed_web_pio.py).
The generated header is committed, so the Arduino IDE needs no extra step.
"""
import gzip
import hashlib
import sys
from pathlib import Path

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".json": "application/json",
    ".png": "image/png",
    ".ico": "image/x-icon",
}


def build(project: Path) -> bool:
    data_dir = project / "data"
    target = project / "src" / "web_assets.h"
    files = sorted(p for p in data_dir.iterdir() if p.is_file() and not p.name.endswith(".gz"))
    lines = [
        "#pragma once",
        "// Generated by tools/embed_web.py from data/. Do not edit by hand.",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct WebAsset {",
        "  const char *path;",
        "  const char *mime;",
        "  const uint8_t *data;",
        "  size_t length;",
        "  const char *etag;",
        "};",
        "",
    ]
    table = []
    for index, path in enumerate(files):
        raw = path.read_bytes()
        packed = gzip.compress(raw, compresslevel=9, mtime=0)
        etag = hashlib.sha1(raw).hexdigest()[:16]
        name = f"WEB_ASSET_{index}"
        lines.append(f"// {path.name}: {len(raw)} bytes, {len(packed)} gzip")
        lines.append(f"static const uint8_t {name}[] = {{")
        for start in range(0, len(packed), 24):
            chunk = packed[start:start + 24]
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
        lines.append("};")
        mime = MIME.get(path.suffix.lower(), "application/octet-stream")
        table.append(f'  {{"/{path.name}", "{mime}", {name}, sizeof({name}), "\\"{etag}\\""}},')
    lines.append("")
    lines.append("static const WebAsset WEB_ASSETS[] = {")
    lines.extend(table)
    lines.append("};")
    lines.append("static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);")
    content = "\n".join(lines) + "\n"
    if target.exists() and target.read_text("utf-8") == content:
        return False
    target.write_text(content, "utf-8")
    return True


if __name__ == "__main__":
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
    changed = build(root)
    print("src/web_assets.h " + ("updated" if changed else "unchanged"))
