# Regenerates src/font5x7.h from Adafruit-GFX glcdfont.c (BSD).
# Usage: python3 tools/mkfont.py path/to/glcdfont.c src/font5x7.h
import re,sys
src=open(sys.argv[1]).read()
body=src[src.index('font[] PROGMEM = {')+18:src.index('};')]
vals=[int(x,16) for x in re.findall(r'0x[0-9A-Fa-f]{2}',body)]
assert len(vals)>=1280, len(vals)
def g(i): return vals[i*5:i*5+5]
extras={0x00C4:0x8E,0x00D6:0x99,0x00DC:0x9A,0x00E4:0x84,0x00F6:0x94,0x00FC:0x81,0x00DF:0xE1,0x00B0:0xF8,
 0x00E9:0x82,0x00E8:0x8A,0x00E0:0x85,0x00E1:0xA0,0x00E7:0x87,0x00F1:0xA4,0x00EA:0x88,0x00E2:0x83,0x00F4:0x93,
 0x00C9:0x90,0x00B7:0xFA,0x2022:0x07,0x2665:0x03,0x2191:0x18,0x2193:0x19,0x2192:0x1A,0x2190:0x1B,
 0x263A:0x01,0x266A:0x0D,0x00BD:0xAB,0x00B5:0xE6,0x00B2:0xFD,0x00A7:0x15,0x00BF:0xA8,0x00A1:0xAD,0x00AB:0xAE,0x00BB:0xAF}
out=[]
out.append('#pragma once\n// Generated by tools/mkfont.py from the Adafruit-GFX "classic" 5x7 font\n// (glcdfont.c, BSD license, Copyright (c) 2012 Adafruit Industries; see LICENSE-FONT.txt).\n// Column-major, bit 0 = top row. ASCII 32..126 plus selected Unicode glyphs.\n#include <stdint.h>\n')
out.append('static const uint8_t FONT5X7_ASCII[95][5] = {')
for c in range(32,127):
    out.append('  {%s}, // %r' % (', '.join('0x%02X'%v for v in g(c)), chr(c)))
out.append('};\n')
out.append('struct Font5x7Extra { uint16_t codepoint; uint8_t cols[5]; };')
out.append('static const Font5x7Extra FONT5X7_EXTRA[] = {')
for cp,idx in sorted(extras.items()):
    out.append('  {0x%04X, {%s}},' % (cp, ', '.join('0x%02X'%v for v in g(idx))))
# Euro sign (custom)
out.append('  {0x20AC, {0x14, 0x3E, 0x55, 0x55, 0x41}},')
out.append('};')
open(sys.argv[2],'w').write('\n'.join(out)+'\n')
